const { test, expect } = require('@playwright/test');
test('@Web Playwright Events Hub', async ({ browser }) => {
    const context = await browser.newContext();
    const page = await context.newPage();
    //eventhub test is successfully passed
    await page.goto('https://eventhub.rahulshettyacademy.com/login');
    await page.getByPlaceholder('you@email.com').fill('thakkarsuraj641@gmail.com');
    await page.getByPlaceholder('••••••').fill('Suraj123@');
    await page.getByRole('button', { name: 'Sign In' }).click();
    await page.waitForLoadState('networkidle');
    await page.getByRole('link', { name: 'Events', exact: true }).click();
    await page.waitForLoadState('networkidle');
    await page.locator('button.inline-flex').click();
    await page.waitForLoadState('networkidle');
    await page.getByLabel('Title').click();
    await page.getByLabel('Title').fill('Bangalore Event');
    await page.getByPlaceholder('Describe the event…').fill('This is a Comedy show event.');
    await page.getByLabel('Category').selectOption('Concert');
    await page.getByLabel('City').fill('Bangalore');
    await page.locator('input#venue').fill('Big Auditorium,Madikeri, Bengaluru-123456');
    await page.getByLabel('Event Date & Time').fill('2026-08-30T14:30');
    await page.locator('input[id="price-($)"]').fill('2.5');
    await page.locator('input#total-seats').fill('500');
    await page.getByLabel('Image URL (optional)').fill('https://media.istockphoto.com/id/1251603742/vector/stand-up-stage-with-mic-red-curtains-and-comedy-show-logo.jpg?s=1024x1024&w=is&k=20&c=53BG2LcFaTyCipxh2yabCphBes_rnqYRLbMciKYMw9k=');
    await page.getByRole('button', { name: '+ Add Event' }).click();
    await page.getByRole('link', { name: 'Events', exact: true }).click();
    await page.waitForLoadState('networkidle');
    await page.locator('article#event-card').last().waitFor();
    await page.getByPlaceholder('Search events, venues…').click();
    await page.getByPlaceholder('Search events, venues…').pressSequentially('Bangalore');
    await page.locator('article#event-card').filter({ hasText: 'Bangalore Event' }).getByRole('link', { name: 'Book Now' }).click();
    await page.locator('input#customerName').fill('Rahul S');
    await page.getByLabel('Email').fill('arre@gmail.com');
    await page.getByLabel('Phone Number').fill('+911234567890');
    await page.getByRole('button', { name: 'Confirm Booking', exact: true }).click();
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: 'View My Bookings' }).click();
    await page.locator('div#booking-card').filter({ hasText: 'B-ZW1E22' }).getByRole('link', { name: 'View Details', exact: true }).click();
    await page.waitForLoadState('networkidle');
    await page.locator('div.p-6').last().waitFor();
    const ticketsRow = await page.locator('div.flex.justify-between:has(span:text-is("Tickets"))');
    const ticketValue = await ticketsRow.locator('span.text-right');
    await expect(ticketValue).toHaveText('1');
});
